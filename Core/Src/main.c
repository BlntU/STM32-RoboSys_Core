Uart_Init(&uart2_ros, &huart2, &hdma_usart2_rx);
Uart_Init(&uart3_relay, &huart3, &hdma_usart3_rx);
Uart_Init(&uart4_adc, &huart4, &hdma_uart4_rx);

HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_raw, 3);

Motor_Start(&motor_R);
