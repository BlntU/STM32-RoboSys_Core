uint16_t trimmed_mean_filter(volatile uint16_t *adcBuffer){

	uint16_t meanVal = 0;
	uint32_t sum = 0;

	// orjinal Adc Buffer'ın kopyası alınarak işlem yapılır
	uint16_t temp_buff[buffSize];
	for(int i = 0; i<buffSize; i++)
	{
		temp_buff[i] = adcBuffer[i];
	}

	// BUBBLE SORT METODU

	for (int i=0; i <buffSize-1; i++){
		for (int j=0; j<buffSize-i-1; j++){
			if(temp_buff[j] > temp_buff[j+1])
			{
				uint16_t tempVal = temp_buff[j];
				temp_buff[j] = temp_buff[j+1];
				temp_buff[j+1] = tempVal;
			}
		}
	}

	// MAX ve MİN değerlerin 2 tanesi atılır

	for (int k = trimSize; k < buffSize - trimSize; k++){
		sum += temp_buff[k];
	}

	meanVal = sum/(buffSize - (2*trimSize));

	return meanVal;
}


